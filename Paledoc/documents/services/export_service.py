"""
Export service for generating Word (.docx) documents from summaries, analysis, and research reports.
Uses python-docx.
"""

import io
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn


def _set_cell_background(cell, fill_hex):
    """Set background color of a table cell."""
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), fill_hex)
    tc_pr.append(shd)


def create_docx_report(report_title: str, report_type_label: str, document_names: list, markdown_content: str, username: str) -> io.BytesIO:
    """
    Generate a styled Word (.docx) document in memory and return as BytesIO.
    """
    doc = Document()

    # Document margins
    sections = doc.sections
    for s in sections:
        s.top_margin = Inches(1.0)
        s.bottom_margin = Inches(1.0)
        s.left_margin = Inches(1.0)
        s.right_margin = Inches(1.0)

    # Title
    title_p = doc.add_paragraph()
    title_p.paragraph_format.space_before = Pt(0)
    title_p.paragraph_format.space_after = Pt(4)
    run_title = title_p.add_run("PALEDOC")
    run_title.font.name = "Calibri"
    run_title.font.size = Pt(11)
    run_title.font.bold = True
    run_title.font.color.rgb = RGBColor(59, 130, 246)  # Primary blue

    # Main Heading
    heading_p = doc.add_paragraph()
    heading_p.paragraph_format.space_after = Pt(12)
    run_heading = heading_p.add_run(report_title)
    run_heading.font.name = "Calibri"
    run_heading.font.size = Pt(22)
    run_heading.font.bold = True
    run_heading.font.color.rgb = RGBColor(15, 23, 42)  # Dark slate

    # Metadata Table / Callout
    meta_table = doc.add_table(rows=3, cols=2)
    meta_table.autofit = True
    meta_data = [
        ("Report Type:", report_type_label),
        ("Source Documents:", ", ".join(document_names) if document_names else "N/A"),
        ("Generated By:", f"{username} (via Paledoc AI Document Intelligence)"),
    ]
    for row_idx, (k, v) in enumerate(meta_data):
        row = meta_table.rows[row_idx]
        cell_k, cell_v = row.cells[0], row.cells[1]
        
        pk = cell_k.paragraphs[0]
        pk.paragraph_format.space_after = Pt(2)
        rk = pk.add_run(k)
        rk.font.name = "Calibri"
        rk.font.size = Pt(9.5)
        rk.font.bold = True
        rk.font.color.rgb = RGBColor(100, 116, 139)
        
        pv = cell_v.paragraphs[0]
        pv.paragraph_format.space_after = Pt(2)
        rv = pv.add_run(v)
        rv.font.name = "Calibri"
        rv.font.size = Pt(9.5)
        rv.font.color.rgb = RGBColor(30, 41, 59)

    doc.add_paragraph().paragraph_format.space_after = Pt(14)

    # Content parsing (Markdown-aware)
    lines = markdown_content.split("\n")
    for line in lines:
        stripped = line.strip()
        if not stripped:
            continue

        if stripped.startswith("### "):
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(14)
            p.paragraph_format.space_after = Pt(4)
            run = p.add_run(stripped[4:])
            run.font.name = "Calibri"
            run.font.size = Pt(13)
            run.font.bold = True
            run.font.color.rgb = RGBColor(30, 41, 59)

        elif stripped.startswith("## "):
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(18)
            p.paragraph_format.space_after = Pt(6)
            run = p.add_run(stripped[3:])
            run.font.name = "Calibri"
            run.font.size = Pt(15)
            run.font.bold = True
            run.font.color.rgb = RGBColor(15, 23, 42)

        elif stripped.startswith("# "):
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(20)
            p.paragraph_format.space_after = Pt(8)
            run = p.add_run(stripped[2:])
            run.font.name = "Calibri"
            run.font.size = Pt(18)
            run.font.bold = True
            run.font.color.rgb = RGBColor(15, 23, 42)

        elif stripped.startswith("- ") or stripped.startswith("* "):
            p = doc.add_paragraph(style='List Bullet')
            p.paragraph_format.space_after = Pt(3)
            # handle simple bold in list item: **text**
            text = stripped[2:]
            _add_markdown_runs(p, text)

        elif stripped.startswith("1. ") or stripped.startswith("2. ") or stripped.startswith("3. ") or stripped.startswith("4. ") or stripped.startswith("5. ") or stripped.startswith("6. ") or stripped.startswith("7. ") or stripped.startswith("8. "):
            p = doc.add_paragraph(style='List Number')
            p.paragraph_format.space_after = Pt(3)
            parts = stripped.split(". ", 1)
            text = parts[1] if len(parts) > 1 else stripped
            _add_markdown_runs(p, text)

        else:
            p = doc.add_paragraph()
            p.paragraph_format.space_after = Pt(6)
            p.paragraph_format.line_spacing = 1.15
            _add_markdown_runs(p, stripped)

    buffer = io.BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer


def _add_markdown_runs(paragraph, text: str):
    """Parse inline **bold** syntax and add formatted runs."""
    parts = text.split("**")
    for idx, part in enumerate(parts):
        if not part:
            continue
        run = paragraph.add_run(part)
        run.font.name = "Calibri"
        run.font.size = Pt(10.5)
        run.font.color.rgb = RGBColor(51, 65, 85)
        if idx % 2 == 1:  # Inside **...**
            run.font.bold = True
            run.font.color.rgb = RGBColor(15, 23, 42)
